function selectObservedPairRun({ pairId = "", runId = "", actualEvents = [], contextEvents = [] }) {
  const wantedPairId = normalizePairId(pairId);
  const wantedRunId = normalizeRunId(runId);
  const groups = new Map();
  for (const event of [...(actualEvents || []), ...(contextEvents || [])]) {
    const lane = eventLane(event);
    const contextEvent = event.kind === "scopelease.mcp_context_event" || event.tool === "scopelease_get_context";
    if (contextEvent) {
      if (lane !== "scopelease-codex") continue;
    } else {
      if (!["default-codex", "scopelease-codex"].includes(lane)) continue;
      if (!isObservedInputPayload(event)) continue;
    }
    const eventPairId = eventPairIdValue(event);
    const eventRunId = normalizeRunId(event.runId || event.meta?.runId);
    if (!eventMatchesPairScope({
      eventPairId,
      eventRunId,
      wantedPairId,
      wantedRunId,
      allowDefaultBaselineRun: lane === "default-codex"
    })) continue;
    const key = wantedRunId ? `${eventPairId || "unpaired"}::${wantedRunId}` : eventPairId || eventRunId || "unscoped";
    const group = groups.get(key) || emptyPairGroup({ pairId: eventPairId, runId: eventRunId || "unscoped" });
    group.latestTimestamp = maxIso(group.latestTimestamp, event.timestamp);
    if (eventPairId && !group.pairId) group.pairId = eventPairId;
    if (eventRunId && !group.runId) group.runId = eventRunId;
    if (contextEvent) {
      if (!group.latestContextEvent || compareIso(event.timestamp, group.latestContextEvent.timestamp) >= 0) {
        group.latestContextEvent = event;
      }
      group.eventCounts.scopeleaseContext += 1;
    } else if (lane === "default-codex") group.defaultEvents.push(event);
    else if (lane === "scopelease-codex") {
      group.scopeleaseWorkEvents.push(event);
      if (eventHasEmbeddedScopeLeaseContext(event)) {
        group.embeddedContextEvents.push(event);
        group.eventCounts.scopeleaseContext += 1;
      }
    }
    groups.set(key, group);
  }
  const candidates = [...groups.values()].map((group) => {
    const scopeleaseContextTokens = Number(group.latestContextEvent?.tokens || 0);
    const embeddedScopeLeaseContextTokens = sumEmbeddedScopeLeaseContextTokens(group.embeddedContextEvents);
    const contextTimestamp = group.latestContextEvent?.timestamp || "";
    const contextRunId = normalizeRunId(group.latestContextEvent?.runId || group.latestContextEvent?.meta?.runId);
    const defaultBaselineRunId = contextRunId ? `${contextRunId}:default-baseline` : "";
    const defaultBucket = latestInputBucket(group.defaultEvents, {
      preferredRunId: defaultBaselineRunId,
      anchorTimestamp: contextTimestamp,
      maxDistanceMs: PAIR_RECENCY_WINDOW_MS
    });
    const scopeleaseWorkBucket = latestInputBucket(group.scopeleaseWorkEvents, {
      preferredRunId: contextRunId,
      anchorTimestamp: contextTimestamp,
      maxDistanceMs: PAIR_RECENCY_WINDOW_MS
    });
    const scopeleaseTokens = scopeleaseContextTokens + scopeleaseWorkBucket.tokens;
    const selectedRunId = contextRunId || scopeleaseWorkBucket.runId || defaultBucket.runId || group.runId;
    return {
      pairId: group.pairId || "",
      runId: selectedRunId === "unscoped" ? "" : selectedRunId,
      selection: pairSelectionLabel({ wantedPairId, wantedRunId, group }),
      latestTimestamp: group.latestTimestamp,
      defaultTokens: defaultBucket.tokens,
      scopeleaseTokens,
      scopeleaseContextTokens,
      scopeleaseWorkTokens: scopeleaseWorkBucket.tokens,
      defaultRunId: defaultBucket.runId || null,
      scopeleaseContextRunId: contextRunId || null,
      scopeleaseWorkRunId: scopeleaseWorkBucket.runId || null,
      measured: defaultBucket.tokens > 0 && scopeleaseWorkBucket.tokens > 0 && (scopeleaseContextTokens > 0 || group.embeddedContextEvents.length > 0),
      embeddedScopeLeaseContextObserved: group.embeddedContextEvents.length > 0,
      embeddedScopeLeaseContextTokens,
      eventCounts: {
        default: defaultBucket.count,
        scopeleaseContext: group.eventCounts.scopeleaseContext,
        scopeleaseWork: scopeleaseWorkBucket.count
      }
    };
  });
  candidates.sort((left, right) => {
    if (left.measured !== right.measured) return left.measured ? -1 : 1;
    return compareIso(right.latestTimestamp, left.latestTimestamp);
  });
  return candidates[0] || {
    pairId: wantedPairId,
    runId: wantedRunId,
    selection: pairSelectionLabel({ wantedPairId, wantedRunId }),
    defaultTokens: 0,
    scopeleaseTokens: 0,
    eventCounts: { default: 0, scopeleaseContext: 0, scopeleaseWork: 0 }
  };
}

function eventMatchesPairScope({
  eventPairId = "",
  eventRunId = "",
  wantedPairId = "",
  wantedRunId = "",
  allowDefaultBaselineRun = false
} = {}) {
  if (wantedPairId && eventPairId !== wantedPairId) return false;
  if (!wantedRunId) return true;
  if (!eventRunId) return false;
  return eventRunId === wantedRunId || (allowDefaultBaselineRun && eventRunId === `${wantedRunId}:default-baseline`);
}

function pairSelectionLabel({ wantedPairId = "", wantedRunId = "", group = {} } = {}) {
  if (wantedPairId && wantedRunId) return "explicit_pair_run";
  if (wantedPairId) return "explicit_pair_id";
  if (wantedRunId) return "explicit_run_id";
  if (!group || !Object.keys(group).length) return "none";
  if (group.pairId) return "latest_pair_id";
  return group.runId === "unscoped" ? "latest_unscoped" : "latest_run_id";
}

function emptyPairGroup({ pairId = "", runId = "unscoped" } = {}) {
  return {
    pairId,
    runId,
    latestTimestamp: "",
    defaultEvents: [],
    scopeleaseWorkEvents: [],
    embeddedContextEvents: [],
    latestContextEvent: null,
    eventCounts: { default: 0, scopeleaseContext: 0, scopeleaseWork: 0 }
  };
}

function latestInputBucket(events = [], { preferredRunId = "", anchorTimestamp = "", maxDistanceMs = 0 } = {}) {
  const wantedRunId = normalizeRunId(preferredRunId);
  const byRun = new Map();
  for (const event of events || []) {
    const runId = normalizeRunId(event.runId || event.meta?.runId) || "unscoped";
    const bucket = byRun.get(runId) || { runId, tokens: 0, count: 0, earliestTimestamp: "", latestTimestamp: "" };
    bucket.tokens += Number(event.tokens || 0);
    bucket.count += 1;
    bucket.earliestTimestamp = bucket.earliestTimestamp
      ? (compareIso(event.timestamp, bucket.earliestTimestamp) < 0 ? event.timestamp : bucket.earliestTimestamp)
      : event.timestamp || "";
    bucket.latestTimestamp = maxIso(bucket.latestTimestamp, event.timestamp);
    byRun.set(runId, bucket);
  }
  let buckets = [...byRun.values()];
  if (anchorTimestamp && maxDistanceMs > 0) {
    buckets = buckets.filter((bucket) => bucketWithinWindow(bucket, anchorTimestamp, maxDistanceMs));
  }
  if (wantedRunId && buckets.some((bucket) => bucket.runId === wantedRunId)) {
    return buckets.find((bucket) => bucket.runId === wantedRunId);
  }
  buckets.sort((left, right) => compareIso(right.latestTimestamp, left.latestTimestamp));
  return buckets[0] || { runId: "", tokens: 0, count: 0, earliestTimestamp: "", latestTimestamp: "" };
}

function bucketWithinWindow(bucket = {}, anchorTimestamp = "", maxDistanceMs = 0) {
  const anchorTime = Date.parse(anchorTimestamp || "");
  if (!Number.isFinite(anchorTime) || maxDistanceMs <= 0) return true;
  const times = [bucket.earliestTimestamp, bucket.latestTimestamp]
    .map((timestamp) => Date.parse(timestamp || ""))
    .filter(Number.isFinite);
  if (!times.length) return true;
  return times.some((time) => Math.abs(time - anchorTime) <= maxDistanceMs);
}

function isObservedInputPayload(event = {}) {
  const phase = String(event.phase || event.meta?.phase || "").trim().toLowerCase();
  if (!phase) return true;
  return ["input", "prompt", "user-prompt", "user_prompt", "explore", "edit"].includes(phase);
}

function isControlledProtocolEvent(event = {}) {
  const source = String(event.source || event.meta?.source || "").toLowerCase();
  return source === "pair-harness" || source.startsWith("pair-harness:") || source.startsWith("live-observed-pair-run:");
}

function eventHasEmbeddedScopeLeaseContext(event = {}) {
  return event.scopeleaseContextEmbedded === true || event.meta?.scopeleaseContextEmbedded === true;
}

function sumEmbeddedScopeLeaseContextTokens(events = []) {
  return events.reduce((sum, event) => sum + Number(event.scopeleaseContextTokens || event.meta?.scopeleaseContextTokens || 0), 0);
}

function filterEventsForWorkIntent(events = [], { workIntent = "", requestKey = "" } = {}) {
  const targetIntent = normalizeRequestKey(workIntent);
  const targetRequest = normalizeRequestKey(requestKey);
  return (events || []).filter((event) => {
    const eventIntent = normalizeRequestKey(event.workIntent || event.meta?.workIntent || "");
    const eventRequest = normalizeRequestKey(event.userRequest || event.request || "");
    if (targetIntent) {
      if (eventIntent && (eventIntent === targetIntent || eventIntent === targetRequest)) return true;
      if (eventRequest && eventRequest === targetRequest) return true;
      return deriveWorkIntent({ request: event.userRequest || event.request || event.requestKey || "" }) === targetIntent;
    }
    return eventRequest === targetRequest;
  });
}

function filterEventsForPairScope(events = [], { pairId = "", runId = "" } = {}) {
  const wantedPairId = normalizePairId(pairId);
  const wantedRunId = normalizeRunId(runId);
  if (!wantedPairId && !wantedRunId) return events;
  return (events || []).filter((event) => {
    return eventMatchesPairScope({
      eventPairId: eventPairIdValue(event),
      eventRunId: normalizeRunId(event.runId || event.meta?.runId),
      wantedPairId,
      wantedRunId,
      allowDefaultBaselineRun: eventLane(event) === "default-codex"
    });
  });
}

function eventLane(event = {}) {
  const value = String(event.lane || event.runLane || event.meta?.lane || event.source || "").toLowerCase().replace(/[_\s]+/g, "-");
  if (value === "scopelease-internal" || value.startsWith("watch:auto")) return "scopelease-internal";
  if (/(default|baseline|without-scopelease|no-scopelease|plain-codex)/.test(value)) return "default-codex";
  if (/(scopelease-codex|with-scopelease|mcp|scopelease)/.test(value)) return "scopelease-codex";
  return "";
}

function eventPairIdValue(event = {}) {
  return normalizePairId(event.pairId || event.pair_id || event.meta?.pairId || event.meta?.pair_id);
}

function normalizeWorkIntent(args = {}, fallback = "", currentRequest = {}, options = {}) {
  const fallbackKey = normalizeRequestKey(fallback);
  const currentKey = normalizeRequestKey(currentRequest.userRequest || "");
  const useCurrent = Boolean(currentRequest.workIntent && (options.forceCurrent || !fallbackKey || fallbackKey === currentKey));
  return deriveWorkIntent({
    request: fallback || currentRequest.userRequest || "",
    workIntent: args.workIntent || args.work_intent || args.intent || (useCurrent ? currentRequest.workIntent : "")
  });
}

function promoteCurrentRunToScopeLease(repo, { currentRequest = {}, workIntent = "", pairId = "", runId = "" } = {}) {
  const root = path.resolve(repo || ".");
  const wantedRunId = normalizeRunId(runId);
  if (!wantedRunId) return { promoted: false, updatedEvents: 0, reason: "missing_run_id" };

  const state = loadState(root) || {};
  let updatedEvents = 0;
  const baselineClones = [];
  const effectivePairId = pairId || currentRequest.pairId || "";
  const effectiveWorkIntent = workIntent || currentRequest.workIntent || "";
  const shouldCloneDefaultBaseline = !hasExistingDefaultPairBaseline(state.actualWorkEvents || [], {
    pairId: effectivePairId,
    workIntent: effectiveWorkIntent,
    runId: wantedRunId
  });
  const actualWorkEvents = (state.actualWorkEvents || []).map((event) => {
    if (normalizeRunId(event.runId || event.meta?.runId) !== wantedRunId) return event;
    if (eventLane(event) === "scopelease-internal") return event;
    if (shouldCloneDefaultBaseline && isDefaultInputEvent(event)) {
      baselineClones.push(defaultBaselineClone(event, { workIntent, pairId, runId: wantedRunId }));
    }
    const next = { ...event, lane: "scopelease-codex" };
    if (workIntent) next.workIntent = workIntent;
    if (pairId) next.pairId = pairId;
    if (JSON.stringify(next) !== JSON.stringify(event)) updatedEvents += 1;
    return next;
  });

  if (updatedEvents > 0 || baselineClones.length > 0) {
    saveState(root, {
      ...state,
      actualWorkEvents: compactPromotedActualWorkEvents([...baselineClones, ...actualWorkEvents])
    });
  }

  if (normalizeRunId(currentRequest.runId) === wantedRunId) {
    writeCurrentRequestState(root, {
      ...currentRequest,
      lane: "scopelease-codex",
      workIntent: workIntent || currentRequest.workIntent || "",
      pairingKey: workIntent || currentRequest.workIntent || "",
      taskIntent: currentRequest.taskIntent || buildTaskIntent({
        request: currentRequest.userRequest || "",
        workIntent: workIntent || currentRequest.workIntent || ""
      }, { pairId: pairId || currentRequest.pairId || "" }),
      pairId: pairId || currentRequest.pairId || "",
      scopeleaseContextSeenAt: new Date().toISOString()
    });
  }

  return {
    promoted: true,
    runId: wantedRunId,
    pairId: pairId || "",
    updatedEvents,
    defaultBaselineClones: baselineClones.length
  };
}

function hasExistingDefaultPairBaseline(events = [], { pairId = "", workIntent = "", runId = "" } = {}) {
  const wantedPairId = normalizePairId(pairId);
  const wantedIntent = normalizeRequestKey(workIntent);
  const wantedRunId = normalizeRunId(runId);
  const wantedBaselineRunId = wantedRunId ? `${wantedRunId}:default-baseline` : "";
  if ((!wantedPairId && !wantedIntent) || !wantedBaselineRunId) return false;
  return (events || []).some((event) => {
    if (eventLane(event) !== "default-codex") return false;
    if (event.autoPairBaseline !== true) return false;
    if (normalizeRunId(event.runId || event.meta?.runId) !== wantedBaselineRunId) return false;
    const eventPairId = eventPairIdValue(event);
    const eventIntent = normalizeRequestKey(event.workIntent || event.meta?.workIntent || "");
    if (wantedPairId) return eventPairId === wantedPairId;
    return wantedIntent && eventIntent === wantedIntent;
  });
}

function isDefaultInputEvent(event = {}) {
  if (eventLane(event) !== "default-codex") return false;
  const phase = String(event.phase || event.meta?.phase || "").trim().toLowerCase();
  return !phase || ["input", "prompt", "user-prompt", "user_prompt"].includes(phase);
}

function defaultBaselineClone(event = {}, { workIntent = "", pairId = "", runId = "" } = {}) {
  const clone = {
    ...event,
    id: `${event.id || hashText(JSON.stringify(event))}:default_baseline`,
    lane: "default-codex",
    runId: `${normalizeRunId(runId) || normalizeRunId(event.runId || event.meta?.runId) || "codex"}:default-baseline`,
    source: `${event.source || "codex-hook"}:auto-default-baseline`,
    label: `${event.label || "Codex user prompt"} baseline`,
    autoPairBaseline: true,
    note: "ScopeLease MCP context promoted this Codex run to scopelease-codex; this clone preserves the pre-ScopeLease visible input as the default-codex baseline for paired measurement."
  };
  if (workIntent) clone.workIntent = workIntent;
  if (pairId) clone.pairId = pairId;
  return clone;
}

function compactPromotedActualWorkEvents(events = []) {
  const output = [];
  const seen = new Set();
  for (const event of events || []) {
    if (!event?.id || seen.has(event.id)) continue;
    seen.add(event.id);
    output.push(event);
    if (output.length >= 500) break;
  }
  return output;
}

function writeCurrentRequestState(repo, state = {}) {
  const root = path.resolve(repo || ".");
  try {
    const dir = path.join(root, ".decision");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "hook-current-request.json"), `${JSON.stringify(state, null, 2)}\n`);
    if (state.userRequest) fs.writeFileSync(path.join(dir, "hook-current-request.txt"), state.userRequest);
  } catch {}
}

function normalizeRunId(value = "") {
  return String(value || "").trim();
}

function normalizePairId(value = "") {
  return String(value || "").trim();
}

function compareIso(left = "", right = "") {
  const leftTime = Date.parse(left || "");
  const rightTime = Date.parse(right || "");
  if (!Number.isFinite(leftTime) && !Number.isFinite(rightTime)) return 0;
  if (!Number.isFinite(leftTime)) return -1;
  if (!Number.isFinite(rightTime)) return 1;
  return leftTime - rightTime;
}

function maxIso(left = "", right = "") {
  return compareIso(left, right) >= 0 ? left : right;
}

