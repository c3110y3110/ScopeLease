function normalizeText(value) {
  if (value === true || value === false || value == null) return "";
  return String(value || "").trim();
}

function explicitRequestArg(args = {}) {
  if (Object.hasOwn(args, "request")) return normalizeText(args.request);
  if (Object.hasOwn(args, "userRequest")) return normalizeText(args.userRequest);
  if (Object.hasOwn(args, "user_request")) return normalizeText(args.user_request);
  return "";
}

function looksLikeStandaloneRequest(value = "") {
  const text = normalizeText(value);
  if (!text) return false;
  if (/(^|[\s"'`])(?:[A-Za-z0-9_.-]+\/)+[A-Za-z0-9_.-]+\.[A-Za-z0-9]+/.test(text)) return true;
  if (/\b(?:src|test|tests|public|docs|examples)\/[^\s]+/.test(text)) return true;
  if (/\b(?:fix|implement|modify|patch|refactor|test|debug|export|record|evaluate|generate|review|audit|inspect|check|harden|secure)\b/i.test(text) && text.length >= 24) return true;
  if (/[가-힣]/.test(text) && /(수정|구현|고쳐|테스트|평가|기록|내보내|생성|보강|추가|검토|리뷰|확인|점검|보안|제품화)/.test(text) && text.length >= 12) return true;
  return false;
}

function looksLikeContinuationRequest(value = "") {
  const text = normalizeText(value).replace(/\s+/g, " ").toLowerCase();
  if (!text || text.length > 140) return false;
  if (looksLikeStandaloneRequest(text)) return false;
  if (/^(ok|okay|yes|yep|go ahead|proceed|continue|do it)\b/.test(text)) return true;
  if (/^(응|ㅇㅇ|그래|좋아|진행|계속|해봐|고쳐|수정|적용|다 고치자|전부 고쳐|모두 고쳐)/.test(text)) return true;
  return /(고치자|진행해|해봐|적용해|수정해)/.test(text) && /(그|다|전부|모두|그렇게|그럼)/.test(text);
}

function looksLikeCurrentScopeRequest(value = "") {
  const text = normalizeText(value).replace(/\s+/g, " ").toLowerCase();
  if (!text || text.length > 160) return false;
  if (looksLikeContinuationRequest(text)) return true;
  if (looksLikeStandaloneRequest(text)) return false;
  return /\b(?:scopelease|mcp|context|ctx)\b/.test(text) || /(컨텍스트|맥락|문맥|호출)/.test(text);
}

