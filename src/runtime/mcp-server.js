function buildDeltaResult(args, repo) {
  const state = loadState(repo) || {};
  const currentRequest = loadCurrentRequestState(repo);
  const explicitRequest = explicitRequestArg(args);
  const useCurrentRequest = Boolean(!explicitRequest || looksLikeContinuationRequest(explicitRequest));
  const requestedText = normalizeText(useCurrentRequest ? (explicitRequest || currentRequest.userRequest) : explicitRequest);
  const latestAnalysis = state.latestAnalysis || null;
  const latestRequest = normalizeText(latestAnalysis?.contextPack?.userRequest?.text || latestAnalysis?.userRequest || "");
  const graphOptions = graphBackendOptionsFromMcpArgs(args);
  const canUseLatestAnalysis = !Object.keys(graphOptions).length &&
    latestAnalysis &&
    normalizeRequestKey(latestRequest) === normalizeRequestKey(requestedText);
  const analysis = canUseLatestAnalysis
    ? latestAnalysis
    : analyzeRepository(repo, analysisOptionsFromMcpArgs(args, { userRequest: requestedText }));
  const userRequest = normalizeText(requestedText || analysis.contextPack?.userRequest?.text || analysis.userRequest);
  const workIntent = normalizeWorkIntent(args, userRequest, currentRequest);
  const currentMatches = normalizeRequestKey(currentRequest.userRequest || "") === normalizeRequestKey(userRequest);
  const runId = normalizeRunId(args.runId || args.run_id || (currentMatches ? currentRequest.runId : ""));
  const pairId = normalizePairId(args.pairId || args.pair_id || args.pair || (currentMatches ? currentRequest.pairId : ""));
  const requestKey = normalizeRequestKey(userRequest);
  const actualEvents = filterEventsForPairScope(
    filterEventsForWorkIntent(state.actualWorkEvents || [], { workIntent, requestKey }),
    { pairId, runId }
  ).filter((event) => !isControlledProtocolEvent(event));
  const contextEvents = filterEventsForPairScope(
    filterEventsForWorkIntent(state.mcpContextEvents || [], { workIntent, requestKey }),
    { pairId, runId }
  ).filter((event) => !isControlledProtocolEvent(event));
  const economy = analysis.contextPack?.tokenEconomy || {};
  const observedWorkTokens = actualEvents.reduce((sum, event) => sum + Number(event.tokens || 0), 0);
  const providedContextTokens = contextEvents.reduce((sum, event) => sum + Number(event.tokens || 0), 0);
  const latestContextEvent = contextEvents[0] || null;
  const inputCandidateTokens = economy.actualInputTokens || latestContextEvent?.tokens || 0;
  const fullRepoTokens = economy.fullRepoTokens || latestContextEvent?.meta?.repoScopeTokens || 0;
  const observedLowerBoundTokens = providedContextTokens + observedWorkTokens;
  const candidateLowerBoundTokens = (inputCandidateTokens || providedContextTokens) + observedWorkTokens;
  const pairedSavings = buildObservedPairSavings({ workIntent, pairId, runId, actualEvents, contextEvents });
  const researchCalibration = buildResearchCalibrationReport({
    repo,
    userRequest,
    workIntent,
    pairId,
    runId,
    pair: pairedSavings
  });
  const agentVisibleDetection = detectAgentVisibleUsage({ repoPath: repo, state });
  const agentVisibleUsage = summarizeAgentVisibleUsage(agentVisibleDetection);
  agentVisibleUsage.pairedLaneStatus = pairedSavings.status;
  agentVisibleUsage.canMeasureAgentVisiblePairDelta = researchCalibration.claimPolicy?.canClaimExactDelta === true;
  agentVisibleUsage.canClaimAgentVisiblePairSavings = researchCalibration.claimPolicy?.canClaimExactSavings === true;
  agentVisibleUsage.canMeasureAgentVisiblePairSavings = researchCalibration.claimPolicy?.canClaimExactSavings === true;
  const result = {
    kind: "scopelease.mcp_delta",
    repo,
    userRequest,
    measurement: {
      boundary: "agent_visible_context_not_provider_billing",
      scopeleaseProvidedContextTokens: providedContextTokens,
      scopeleaseInputCandidateTokens: inputCandidateTokens,
      observedWorkPayloadTokens: observedWorkTokens,
      observedLowerBoundTokens,
      candidateLowerBoundTokens,
      agentVisibleMeasured: Boolean(providedContextTokens || observedWorkTokens),
      providerUsageExcluded: true
    },
    observedPairSavings: pairedSavings,
    researchCalibration,
    agentVisibleUsage,
    contextCandidate: {
      repoScopeTokens: fullRepoTokens,
      inputCandidateTokens,
      label: "ScopeLease input candidate size and repository scope size; not a savings percentage"
    },
    events: {
      mcpContextEvents: contextEvents.length,
      actualWorkEvents: actualEvents.length,
      providerUsageEventsExcluded: (state.modelUsageEvents || []).length
    },
    caveat: "Pair delta is valid only for a paired work intent: observed default-codex input n versus observed scopelease-codex input m. Positive savings additionally require n > m. Provider/API billing usage and full repository size are excluded from this metric."
  };
  result._internal = {
    latestContextEvent,
    analysis,
    state,
    currentRequest
  };
  return result;
}

function stripInternalFields(value = {}) {
  const { _internal, ...publicValue } = value;
  return publicValue;
}

