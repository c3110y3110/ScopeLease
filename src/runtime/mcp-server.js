const SERVER_NAME = "scopelease";
const SERVER_VERSION = "0.1.0";
const DEFAULT_PROTOCOL_VERSION = "2024-11-05";
const PAIR_RECENCY_WINDOW_MS = 60 * 60 * 1000;

export function startMcpServer({ repoPath = "." } = {}) {
  const defaultRepo = path.resolve(repoPath);
  const rl = readline.createInterface({
    input: process.stdin,
    crlfDelay: Infinity
  });

  let queue = Promise.resolve();
  rl.on("line", (line) => {
    queue = queue
      .then(() => processMcpLine(line, { defaultRepo }))
      .catch((error) => {
        writeMessage(errorResponse(null, -32603, error.message || String(error)));
      });
  });
}

async function processMcpLine(line, { defaultRepo }) {
  const text = String(line || "").trim();
  if (!text) return;
  let message;
  try {
    message = JSON.parse(text);
  } catch (error) {
    writeMessage(errorResponse(null, -32700, `Parse error: ${error.message}`));
    return;
  }

  try {
    const response = await handleMcpMessage(message, { defaultRepo });
    if (response) writeMessage(response);
  } catch (error) {
    if (message.id !== undefined) {
      writeMessage(errorResponse(message.id, -32603, error.message || String(error)));
    }
  }
}

async function handleMcpMessage(message, { defaultRepo }) {
  const { id, method, params = {} } = message;
  if (!method) return id === undefined ? null : errorResponse(id, -32600, "Invalid request");

  if (method === "initialize") {
    return successResponse(id, {
      protocolVersion: params.protocolVersion || DEFAULT_PROTOCOL_VERSION,
      capabilities: {
        tools: {},
        resources: {}
      },
      serverInfo: {
        name: SERVER_NAME,
        version: SERVER_VERSION
      }
    });
  }

  if (method === "notifications/initialized" || id === undefined) return null;
  if (method === "ping") return successResponse(id, {});
  if (method === "tools/list") return successResponse(id, { tools: mcpTools() });

  if (method === "tools/call") {
    const name = String(params.name || "");
    const args = params.arguments && typeof params.arguments === "object" ? params.arguments : {};
    const result = await callTool(name, args, { defaultRepo });
    return successResponse(id, result);
  }

  if (method === "resources/list") {
    return successResponse(id, {
      resources: [
        {
          uri: `scopelease://state`,
          name: "ScopeLease state",
          description: "Latest ScopeLease state for the configured repository.",
          mimeType: "application/json"
        },
        {
          uri: `scopelease://context-pack`,
          name: "ScopeLease context pack",
          description: "Latest compact context pack generated by ScopeLease.",
          mimeType: "application/json"
        }
      ]
    });
  }

  if (method === "resources/read") {
    const state = loadState(defaultRepo) || {};
    const uri = String(params.uri || "");
    if (uri === "scopelease://state") return successResponse(id, resourceText(uri, state));
    if (uri === "scopelease://context-pack") return successResponse(id, resourceText(uri, state.latestAnalysis?.contextPack || {}));
    return errorResponse(id, -32602, `Unknown resource: ${uri}`);
  }

  return errorResponse(id, -32601, `Method not found: ${method}`);
}

async function callTool(name, args, { defaultRepo }) {
  if (name === "scopelease_get_context") return toolGetContext(args, defaultRepo);
  if (name === "scopelease_explain_delta") return toolExplainDelta(args, defaultRepo);
  if (name === "scopelease_measure") return toolMeasure(args, defaultRepo);
  if (name === "scopelease_record_usage") return toolRecordUsage(args, defaultRepo);
  if (name === "scopelease_detect_agent_usage" || name === "scopelease_detect_codex_usage") return toolDetectAgentUsage(args, defaultRepo);
  if (name === "scopelease_research_calibration") return toolResearchCalibration(args, defaultRepo);
  if (name === "scopelease_guard") return toolGuard(args, defaultRepo);
  if (name === "scopelease_approve") return toolApprove(args, defaultRepo);
  if (name === "scopelease_record_fatigue") return toolRecordFatigue(args, defaultRepo);
  throw new Error(`Unknown tool: ${name}`);
}

function toolGetContext(args, defaultRepo) {
  const repo = resolveRepo(args.repo, defaultRepo);
  const currentRequest = loadCurrentRequestState(repo);
  const envWorkIntent = normalizeText(process.env.SCOPELEASE_WORK_INTENT || "");
  const envPairId = normalizePairId(process.env.SCOPELEASE_PAIR_ID || "");
  const envRunId = normalizeRunId(process.env.SCOPELEASE_RUN_ID || "");
  const explicitRequest = explicitRequestArg(args);
  const hasExplicitRequest = Boolean(explicitRequest);
  const userRequest = normalizeText(explicitRequest || currentRequest.userRequest);
  const currentMatches = normalizeRequestKey(currentRequest.userRequest || "") === normalizeRequestKey(userRequest);
  const explicitRunOrPair = Boolean(args.runId || args.run_id || args.pairId || args.pair_id || args.pair);
  const explicitIntent = Boolean(args.workIntent || args.work_intent || args.intent);
  const useCurrentScope = Boolean(
    currentRequest.userRequest &&
    currentRequest.runId &&
    currentRequest.pairId &&
    !explicitRunOrPair &&
    !explicitIntent &&
    (!hasExplicitRequest || looksLikeCurrentScopeRequest(explicitRequest))
  );
  const effectiveRequest = useCurrentScope ? currentRequest.userRequest || userRequest : userRequest;
  const workIntent = normalizeWorkIntent({
    ...args,
    workIntent: args.workIntent || args.work_intent || args.intent || (useCurrentScope ? "" : envWorkIntent)
  }, effectiveRequest, currentRequest, { forceCurrent: useCurrentScope });
  const runId = normalizeRunId(
    args.runId || args.run_id || ((currentMatches || useCurrentScope) ? currentRequest.runId : "") || envRunId
  );
  const pairId = normalizePairId(
    args.pairId || args.pair_id || args.pair || ((currentMatches || useCurrentScope) ? currentRequest.pairId : "") || envPairId
  );
  const budget = Number(args.budget || 8000);
  const format = ["prompt", "summary", "payload"].includes(args.format) ? args.format : "payload";
  const contextMode = args.mode || args.contextMode || args.context_mode || "auto";
  const analysis = analyzeRepository(repo, analysisOptionsFromMcpArgs(args, { budget, userRequest: effectiveRequest }));
  const payload = buildAgentInputPayload(analysis.contextPack, { userRequest: effectiveRequest });
  const adaptiveContext = buildAdaptiveContext({
    repoPath: repo,
    request: effectiveRequest,
    analysis,
    payload,
    mode: contextMode
  });
  const contextText = shouldReturnFullContext(adaptiveContext)
    ? payload.codexInput?.text || JSON.stringify(payload.structuredContext?.input || {})
    : adaptiveContext.text;
  const taskIntent = buildTaskIntent({ request: effectiveRequest, workIntent }, {
    pairId,
    paths: (payload.readPlan || []).map((item) => item.path || item.id || item.label).filter(Boolean),
    decisionNeeded: payload.decisionGate?.canAutoApplyPatch === false
  });
  const measurementState = loadState(repo) || {};
  const measurementMode = measurementModeForState(measurementState);
  const shouldRecordContext = args.record !== false && shouldRecordAutomaticMeasurement(measurementState, "mcp:scopelease_get_context");
  const promotion = shouldRecordContext
    ? promoteCurrentRunToScopeLease(repo, { currentRequest, workIntent, pairId, runId })
    : { promoted: false, reason: "measurement_mode_off" };
  const event = shouldRecordContext ? recordMcpContextEvent(repo, {
    tool: "scopelease_get_context",
    userRequest: payload.userRequest?.text || analysis.contextPack?.userRequest?.text || userRequest,
    text: contextText,
    baselineTokens: 0,
    meta: {
      budget,
      format,
      mode: contextMode,
      adaptiveContext: {
        mode: adaptiveContext.mode,
        requestedMode: adaptiveContext.requestedMode,
        tokens: adaptiveContext.tokens,
        chars: adaptiveContext.chars,
        decision: adaptiveContext.decision
      },
      workIntent,
      taskIntent,
      requestHash: useCurrentScope ? (currentRequest.requestHash || requestHash(effectiveRequest)) : requestHash(effectiveRequest),
      runId,
      pairId,
      promotion,
      repoScopeTokens: analysis.contextPack?.tokenEconomy?.fullRepoTokens || 0,
      contextField: payload.structuredContext?.field || "contextPack.agentContext",
      codexInputField: shouldReturnFullContext(adaptiveContext) ? payload.field || "codexInput.text" : "adaptiveContext.text"
    }
  }) : null;
  const summary = summarizeContextPayload(analysis, payload, event, { pairId, taskIntent, adaptiveContext });
  summary.measurementMode = measurementMode;
  summary.recorded = Boolean(event);

  if (format === "prompt") {
    return toolResult(contextText || "", summary);
  }

  if (format === "summary") {
    return toolResult(JSON.stringify(summary, null, 2), summary);
  }

  return toolResult(JSON.stringify({
    ...summary,
    codexInput: payload.codexInput,
    structuredContext: payload.structuredContext,
    decisionGate: payload.decisionGate,
    usefulness: payload.usefulness,
    readPlan: payload.readPlan,
    avoidPlan: payload.avoidPlan,
    traceLedger: payload.traceLedger
  }, null, 2), summary);
}

