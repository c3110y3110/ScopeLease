function toolApprove(args, defaultRepo) {
  const repo = resolveRepo(args.repo, defaultRepo);
  const action = args.action || {};
  const choiceId = normalizeText(args.choiceId || args.choice) || "allow_scoped_patch";
  const analysis = analyzeRepository(repo, analysisOptionsFromMcpArgs(args, {
    userRequest: normalizeText(args.request || args.userRequest)
  }));
  const state = loadState(repo) || {};
  const guardVerdict = evaluateAgentAction({ action, analysis, state });
  if (guardVerdict.verdict !== "ask_once" || !guardVerdict.decisionBundle) {
    throw new Error("No current guard decision requires approval for this action.");
  }
  const decisionBundle = guardVerdict.decisionBundle;
  const lease = approveDecisionBundle({
    analysis,
    state,
    decisionBundle,
    choiceId,
    grantedBy: normalizeText(args.grantedBy) || "human"
  });
  const next = {
    ...state,
    approvalLeases: compactApprovalLeases([lease, ...(state.approvalLeases || [])])
  };
  saveState(repo, next);
  const fatigue = recordDecisionFatigueEvent(repo, {
    type: "approval_lease_created",
    request: normalizeText(args.request || args.userRequest),
    source: "mcp:scopelease_approve",
    actor: normalizeText(args.grantedBy) || "human",
    lease,
    decisionBundleId: decisionBundle.id,
    verdict: guardVerdict.verdict,
    actionGrant: guardVerdict.actionGrant,
    action
  });
  const result = {
    ok: true,
    lease,
    fatigueEvent: fatigue.event,
    previousVerdict: guardVerdict,
    note: "Approval lease recorded. Re-run scopelease_guard for the same request/action before applying."
  };
  return toolResult(JSON.stringify(result, null, 2), result);
}

