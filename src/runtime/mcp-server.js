function loadCurrentRequestState(repo) {
  const root = path.resolve(repo || ".");
  const jsonPath = path.join(root, ".decision", "hook-current-request.json");
  try {
    const parsed = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
    return parsed && typeof parsed === "object" ? parsed : {};
  } catch {}
  try {
    const userRequest = fs.readFileSync(path.join(root, ".decision", "hook-current-request.txt"), "utf8").trim();
    return userRequest ? {
      userRequest,
      workIntent: deriveWorkIntent({ request: userRequest }),
      pairingKey: deriveWorkIntent({ request: userRequest }),
      taskIntent: buildTaskIntent({ request: userRequest }),
      requestHash: requestHash(userRequest),
      runId: ""
    } : {};
  } catch {
    return {};
  }
}

function compactMcpContextEvents(events = []) {
  const output = [];
  const seen = new Set();
  for (const event of events) {
    if (!event?.id || seen.has(event.id)) continue;
    seen.add(event.id);
    output.push(event);
    if (output.length >= 120) break;
  }
  return output;
}

function compactApprovalLeases(leases = []) {
  const output = [];
  const seen = new Set();
  for (const lease of leases) {
    if (!lease?.id || seen.has(lease.id)) continue;
    seen.add(lease.id);
    output.push(lease);
    if (output.length >= 40) break;
  }
  return output;
}

function hashText(value) {
  return createHash("sha256").update(String(value || "")).digest("hex").slice(0, 16);
}
